-- Web-app tables in screener_app (docs/netlify-production-plan.md §4.1): the SQLite app database, ported.
--
-- Decisions (recorded here, as the plan asks):
--  * D4: the code's names win. screener_app.user_prompts -> prompts, watchlist_items -> watchlist_entries.
--    The warehouse drafts of prompts / watchlists / watchlist_items / prompt_conditions were never read by the
--    web app, so they are reshaped to the app's columns. Each reshape is guarded: if the old table holds rows,
--    the migration aborts (and rolls back) instead of dropping data.
--  * Ids stay numeric and user-visible (3 Oct decision): bigint identity BY DEFAULT, so seeds, tests and the
--    one-off SQLite data move can insert explicit ids.
--  * Value shapes are kept compatible with the app code: JSON columns are jsonb, dates are date, instants are
--    timestamptz; the node driver hands them to the code as the same ISO / JSON strings SQLite stored
--    (see src/server/db/pg.ts type parsers). 0/1 flags stay smallint with a CHECK.
--  * No eval/golden tables here (12 Oct rule).
--  * search_path: the app uses unqualified names, and a pooled connection cannot rely on a session SET, so
--    the role the migration runs as gets search_path = screener_app, public.

do $$
begin
  if exists (select 1 from screener_app.user_prompts) then
    raise exception 'screener_app.user_prompts has rows; 0011 reshapes it and will not drop data';
  end if;
  if exists (select 1 from screener_app.watchlists) then
    raise exception 'screener_app.watchlists has rows; 0011 reshapes it and will not drop data';
  end if;
  if exists (select 1 from screener_app.watchlist_items) then
    raise exception 'screener_app.watchlist_items has rows; 0011 replaces it and will not drop data';
  end if;
  if exists (select 1 from screener_app.prompt_conditions) then
    raise exception 'screener_app.prompt_conditions has rows; 0011 replaces it and will not drop data';
  end if;
end $$;

