  structure           text check (structure in ('literal','t1_literal')),
  spec_json           jsonb,
  needs_input_json    jsonb,
  answers_json        jsonb,
  hypothesis          text,
  kill_criterion      text,
  status              text not null default 'open' check (status in ('open','confirmed','abandoned')),
  confirmed_prompt_id bigint,
  source_phrases_json jsonb,
  unsupported_json    jsonb,
  copied_from_prompt_id bigint,
  program_json        jsonb,
  program_clauses_json jsonb,
  program_normalised  text,
  created_at          timestamptz not null,
  updated_at          timestamptz not null
);
create index ix_drafts_user on screener_app.prompt_drafts (user_id, status);

-- ---------------------------------------------------------------------------------------------------------
-- prompts: replace the warehouse draft user_prompts. Foreign keys that point at it (from prompt_history,
-- forward_testing) are remembered, dropped, and re-pointed at the new table.
drop table screener_app.prompt_conditions;
drop view screener_app.v_watchlist_live;
drop table screener_app.watchlist_items;

create temp table _prompt_fks on commit drop as
select c.conrelid::regclass::text as tbl, c.conname,
       replace(pg_get_constraintdef(c.oid), 'user_prompts', 'prompts') as def
from pg_constraint c
where c.contype = 'f' and c.confrelid = 'screener_app.user_prompts'::regclass;

do $$
declare r record;
begin
  for r in select * from _prompt_fks loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
  end loop;
end $$;

drop table screener_app.user_prompts;

create table screener_app.prompts (
  prompt_id             bigint generated by default as identity primary key,
  owner_user_id         bigint not null references screener_app.users,
  draft_id              bigint not null unique references screener_app.prompt_drafts,
  title                 text not null,
  prompt_text           text not null check (length(prompt_text) <= 2000),
  structure             text not null check (structure in ('literal','t1_literal')),
  spec_json             jsonb not null,
  spec_hash             text not null,
  status                text not null default 'confirmed' check (status in ('confirmed','superseded','retired')),
  parent_prompt_id      bigint references screener_app.prompts,
  version               integer not null default 1,
  hypothesis            text not null,
  kill_criterion        text not null,
  tracks_stock_arm      text check (tracks_stock_arm in ('literal','t1_literal')),
  review_week           integer,
  confirmed_at          timestamptz not null,
  closed_at             timestamptz,
  visibility            text not null default 'private' check (visibility in ('private','shared')),
  copied_from_prompt_id bigint references screener_app.prompts,
  resolved_json         jsonb
);
create index ix_prompts_owner on screener_app.prompts (owner_user_id, status);
create unique index ux_prompts_owner_spec on screener_app.prompts (owner_user_id, spec_hash) where status = 'confirmed';

alter table screener_app.prompt_drafts
  add constraint prompt_drafts_parent_prompt_fk    foreign key (parent_prompt_id)      references screener_app.prompts,
  add constraint prompt_drafts_confirmed_prompt_fk foreign key (confirmed_prompt_id)   references screener_app.prompts,
  add constraint prompt_drafts_copied_from_fk      foreign key (copied_from_prompt_id) references screener_app.prompts;

do $$
declare r record;
begin
  for r in select * from _prompt_fks loop
    execute format('alter table %s add constraint %I %s', r.tbl, r.conname, r.def);
  end loop;
end $$;

